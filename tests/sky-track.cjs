const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const Module = require('node:module');
const path = require('node:path');
const result = esbuild.buildSync({ entryPoints: [path.join(__dirname, '../src/lib/skyTrack.ts')], bundle: true, write: false, platform: 'node', format: 'cjs' });
const mod = new Module('sky-track-tests'); mod._compile(result.outputFiles[0].text, 'sky-track.js');
const { skyTrackPosition, skyTrackSegments, skyTrackWindow } = mod.exports;
const sample = (hour, azimuth = 10, elevation = 20) => ({ datetime_utc: new Date(Date.UTC(2027, 1, 1, hour)).toISOString(), azimuth, elevation, distance: 384400 });
const instant = hour => sample(hour).datetime_utc;
const wrap = [sample(0, 359), sample(1, 1)];
const mid = skyTrackPosition(wrap, '2027-02-01T00:30:00Z', 1);
assert.ok(mid.azimuth < 0.001 || mid.azimuth > 359.999, 'azimuth wrap must not send Earth across the sky');
assert.equal(mid.distance, 384400);
const zenith = skyTrackPosition([sample(0, 0, 89), sample(1, 180, 89)], '2027-02-01T00:30:00Z', 1);
assert.ok(zenith.elevation > 89.999, 'zenith crossing must pass overhead instead of making a sideways loop');
assert.deepEqual(skyTrackSegments([sample(0), sample(1), sample(2, null), sample(3), sample(4)], 1).map(s => s.length), [2, 2]);
assert.equal(skyTrackPosition([sample(0), sample(2)], instant(1), 1), null, 'never interpolate across missing data');
assert.equal(skyTrackPosition(wrap, instant(2), 1), null, 'never extrapolate stale positions');
assert.equal(skyTrackPosition([sample(0), sample(1, NaN)], '2027-02-01T00:30:00Z', 1), null);
assert.equal(skyTrackPosition(wrap, instant(0), 1).azimuth, 359);
assert.equal(skyTrackPosition(wrap, instant(1), 1).azimuth, 1);
console.log('Sky-track wraparound, zenith, missing-data and time synchronization checks passed.');

const clipped = skyTrackWindow([sample(0), sample(1), sample(2), sample(3)], '2027-02-01T00:30:00Z', '2027-02-01T02:30:00Z', 1);
assert.equal(clipped[0].datetime_utc, '2027-02-01T00:30:00.000Z');
assert.equal(clipped.at(-1).datetime_utc, '2027-02-01T02:30:00.000Z');
assert.deepEqual(skyTrackSegments(clipped, 1).map(s => s.length), [4]);
const missingBoundary = skyTrackWindow([sample(0), sample(1, null), sample(2), sample(3)], '2027-02-01T00:30:00Z', instant(3), 1);
assert.equal(missingBoundary[0].datetime_utc, sample(1).datetime_utc, 'retain the missing sample rather than invent a boundary position');
assert.deepEqual(skyTrackSegments(missingBoundary, 1).map(s => s.length), [2]);
assert.deepEqual(skyTrackWindow(wrap, instant(1), instant(0), 1), []);
assert.deepEqual(skyTrackWindow(wrap, instant(3), instant(4), 1), []);
console.log('Finite Earth-track windows preserve interpolation and real data gaps.');
