const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const targets = await (await fetch('http://127.0.0.1:9227/json')).json();
  const target = targets.find(t => t.type === 'page' && t.url.includes('5173'));
  if (!target) throw new Error('Preview page unavailable');
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { ws.onopen = resolve; ws.onerror = reject; });
  let id = 0; const pending = new Map(); const errors = [];
  ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); if (m.error) p.reject(new Error(m.error.message)); else p.resolve(m.result); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); };
  const call = (method, params = {}) => new Promise((resolve, reject) => { const n = ++id; pending.set(n, {resolve,reject}); ws.send(JSON.stringify({id:n,method,params})); });
  const evaluate = async expression => { const r = await call('Runtime.evaluate', {expression, returnByValue: true, awaitPromise: true}); if (r.exceptionDetails) throw new Error(r.exceptionDetails.text); return r.result.value; };
  const waitFor = async expression => { const until = Date.now() + 45000; while (Date.now() < until) { if (await evaluate(expression)) return; await new Promise(r => setTimeout(r, 300)); } throw new Error('Timed out: ' + expression); };
  const click = text => evaluate(`(() => { const b = [...document.querySelectorAll('button')].find(b => b.textContent.includes(${JSON.stringify(text)})); if (!b) throw new Error('Button missing'); b.click(); return true; })()`);
  const input = (label, value) => evaluate(`(() => { const l = [...document.querySelectorAll('.science-card label')].find(l => l.textContent.includes(${JSON.stringify(label)})); const e=l.querySelector('input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(e, ${JSON.stringify(String(value))}); e.dispatchEvent(new Event('input', {bubbles:true})); })()`);
  await call('Runtime.enable'); await call('Page.enable');
  await waitFor("!!document.querySelector('.sl-forecast-page')");
  await click('Calculate Diurnal Forecast');
  await waitFor("document.querySelectorAll('.forecast-chart').length === 4");
  assert.equal(await evaluate("document.querySelector('#science-window-title') === null"), true, 'finder has its own page');
  await evaluate("[...document.querySelectorAll('.sl-mode-btn')].find(b=>b.textContent.includes('Science Windows')).click()");
  await waitFor("!!document.querySelector('#science-page-title') && !!document.querySelector('#science-window-title')");
  assert.equal(await evaluate("location.hash"), '#science-windows');
  await input('Minimum temperature', -300); await input('Maximum temperature', 300);
  await evaluate("(() => { const e=[...document.querySelectorAll('.science-checks input')][1]; if(e.checked)e.click(); })()");
  await waitFor("document.querySelectorAll('.science-card tbody tr').length > 0");
  await click('Show in charts');
  await waitFor("document.querySelectorAll('.forecast-chart').length === 4 && location.hash === '#forecast'");
  assert.equal(await evaluate("document.querySelectorAll('.chart-cursor').length"), 4);
  await evaluate("[...document.querySelectorAll('.sl-mode-btn')].find(b=>b.textContent.includes('Science Windows')).click()");
  await waitFor("!!document.querySelector('#science-window-title')");
  await input('Maximum temperature', -301);
  await waitFor("document.querySelector('.science-card [role=alert]') !== null");
  await input('Maximum temperature', 300);
  await evaluate("[...document.querySelectorAll('.sl-mode-btn')].find(b=>b.textContent.trim() === 'Forecast').click()");
  await waitFor("document.querySelectorAll('.forecast-chart').length === 4");
  fs.mkdirSync('frontend/tests/previews', {recursive:true});
  const screenshot = async name => { const r = await call('Page.captureScreenshot', {format:'png'}); fs.writeFileSync('frontend/tests/previews/'+name+'.png', Buffer.from(r.data,'base64')); };
  await evaluate("document.querySelector('.sl-forecast-page').scrollTop = document.querySelector('.science-cursor').offsetTop - 180");
  await screenshot('forecast-desktop');
  console.log('Forecast controls, science windows and shared cursors passed.');
  await evaluate("[...document.querySelectorAll('.sl-mode-btn')].find(b=>/Compar/i.test(b.textContent)).click()");
  await waitFor("!!document.querySelector('.science-card')");
  assert.equal(await evaluate("document.querySelectorAll('.cmp-step-num').length"), 0, 'comparison has no numbered steps');
  assert.equal(await evaluate("/step [123]/i.test(document.querySelector('.site-comparison-container').textContent)"), false);
  await click('Compare forecasts');
  await waitFor("document.querySelectorAll('.forecast-chart').length === 4");
  assert.equal(await evaluate("document.querySelectorAll('.forecast-chart polyline').length"), 12);
  await screenshot('comparison-desktop');
  console.log('Three-site synchronized comparison passed.');
  await evaluate("[...document.querySelectorAll('.sl-mode-btn')].find(b=>/Lunar|Moon/i.test(b.textContent)).click()");
  await waitFor("!!document.querySelector('.map-layer-controls')"); await click('Illumination');
  await waitFor("document.querySelector('.science-map-legend') !== null");
  await click('Temperature');
  await evaluate(`(() => { const file=new File([JSON.stringify({source:'Browser test fixture / spherical datum',resolution:'Discrete test points',points:[{lat:-89.54,lon:0,elevation_m:1200,slope_deg:14},{lat:-86.04,lon:2.7,elevation_m:1500,slope_deg:8}]})], 'test.json', {type:'application/json'}); const dt=new DataTransfer();dt.items.add(file); const e=document.querySelector('.map-layer-controls input[type=file]');e.files=dt.files;e.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await waitFor("document.querySelector('.map-layer-controls').textContent.includes('2 points')");
  await click('Slope');
  await waitFor("!!document.querySelector('.sl-viewer canvas')");
  await new Promise(r => setTimeout(r, 2500));
  await screenshot('map-desktop');
  await click('Remove imported data');
  await click('Illumination');
  await call('Emulation.setDeviceMetricsOverride', {width:390,height:844,deviceScaleFactor:1,mobile:true});
  await screenshot('map-mobile');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= window.innerWidth'), true, 'mobile map must fit viewport');
  await evaluate("[...document.querySelectorAll('.sl-mode-btn')].find(b=>/Forecast/i.test(b.textContent)).click()");
  await waitFor("document.querySelectorAll('.forecast-chart').length === 4");
  await evaluate("document.querySelector('.science-cursor').scrollIntoView()");
  await screenshot('forecast-mobile');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= window.innerWidth'), true, 'mobile forecast must fit viewport');
  assert.deepEqual(errors, [], 'no browser runtime exceptions');
  console.log('Map layer switching, terrain import/removal and mobile layouts passed.');
  await call('Browser.close'); ws.close();
})().catch(e=>{console.error(e);process.exit(1)});
